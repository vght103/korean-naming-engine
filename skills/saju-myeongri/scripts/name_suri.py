SANGSAENG = {('목','화'),('화','토'),('토','금'),('금','수'),('수','목')}
SANGGEUK = {('목','토'),('토','수'),('수','화'),('화','금'),('금','목')}

def suri(n):
    if n <= 0:
        return None
    k = n if n <= 81 else ((n - 1) % 81) + 1
    g, u, gil = SURI81[k]
    deung = ('大吉' if k in DAEGIL else '吉') if gil == '길' else gil
    r = {'수': n, '적용수': k, '격': g, '운': u, '길흉': gil, '등급': deung}
    if k in CONTESTED:
        r['이설'] = CONTESTED[k]
    return r

def rel(a, b):
    """a→b 방향으로 판정. 순생(a生b)과 역생(b生a)을 구분한다.

    구 버전은 무방향이라 金→土(역생)를 土→金(순생)과 같은 '상생'으로 셌다.
    SKILL.md 의 "순차 상생이 최상" 기준과 어긋나므로 2026-08-31 방향성을 도입했다.
    길흉 판정 자체(상생/상극/비화)는 바뀌지 않으므로 기존 회귀는 영향 없다.
    """
    if (a, b) in SANGSAENG:
        return '상생(순생)'
    if (b, a) in SANGSAENG:
        return '상생(역생)'
    if (a, b) in SANGGEUK or (b, a) in SANGGEUK:
        return '상극'
    return '비화(같은 오행)'

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--name', required=True, help='한글 이름 (성 포함)')
    p.add_argument('--strokes', help='한자 원획수, 쉼표 구분 (성 포함, 글자 순서대로)')
    p.add_argument('--surname-chars', type=int, default=1, help='성 글자 수 (기본 1)')
    a = p.parse_args()

    out = {'이름': a.name}

    # 발음오행
    ohs = []
    for ch in a.name:
        code = ord(ch) - 0xAC00
        if 0 <= code < 11172:
            cho = CHOSEONG[code // 588]
            ohs.append({'글자': ch, '초성': cho, '오행': CHO_OHENG[cho]})
    rels = [f"{ohs[i]['오행']}-{ohs[i+1]['오행']}: {rel(ohs[i]['오행'], ohs[i+1]['오행'])}"
            for i in range(len(ohs) - 1)]
    out['발음오행'] = {'배열': ohs, '관계': rels,
                      '기준': '통용 발음오행(ㅇㅎ=토, ㅁㅂㅍ=수). 훈민정음 해례본 기준은 반대임을 유의.'}

    # 수리 사격
    if a.strokes:
        st = [int(x) for x in a.strokes.split(',')]
        sc = a.surname_chars
        surname = sum(st[:sc])
        given = st[sc:]
        g1 = given[0] if given else 0
        g2 = given[1] if len(given) > 1 else 0
        won = g1 + g2 if g2 else g1          # 원격 (초년운)
        hyung = surname + g1                  # 형격 (중년/주운)
        lee = surname + g2 if g2 else surname # 이격 (말년/부운)
        jeong = surname + sum(given)          # 정격 (총운/일생)
        out['수리사격'] = {
            '획수': {'성': surname, '이름': given},
            '원격(초년 1~20대)': suri(won),
            '형격(청장년 20~40대)': suri(hyung),
            '이격(중년 40~60대)': suri(lee),
            '정격(총운/말년)': suri(jeong),
            '기준': '구마사키식 사격 수리, 한자 원획법(강희자전) 획수',
        }
        grades = [suri(x)['길흉'] for x in (won, hyung, lee, jeong)]
        deungs = [suri(x)['등급'] for x in (won, hyung, lee, jeong)]
        out['종합'] = {'길': grades.count('길'), '흉': grades.count('흉'),
                       '반길반흉': grades.count('반길반흉'),
                       '大吉': deungs.count('大吉'), '吉': deungs.count('吉'),
                       '평가': '사격 모두 길수' if grades.count('길') == 4 else
                               ('흉수 포함 — 세부 해석 필요' if '흉' in grades else '길·반길 혼재')}

    print(json.dumps(out, ensure_ascii=False, indent=2))

if __name__ == '__main__':
    main()
